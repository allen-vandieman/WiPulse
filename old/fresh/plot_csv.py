def extract_all_csi_from_csv(csv_file):
    """Extract all CSI data from CSV file generated by live_monitor.py"""
    
    print(f"Loading CSI data from {csv_file}...")
    
    # Read the CSV
    df = pd.read_csv(csv_file)
    
    print(f"CSV shape: {df.shape} rows x {df.shape[1]} columns")
    
    # Extract metadata columns
    timestamps = df['ts'].values
    seq_nums = df['seq_num'].values
    cores = df['core'].values
    spatial_streams = df['spatial_stream'].values
    
    # Identify complex columns (I and Q pairs)
    complex_cols = [col for col in df.columns if col not in ['ts', 'seq_num', 'core', 'spatial_stream']]
    
    # Determine number of subcarriers
    n_sc = len(complex_cols) // 2
    print(f"Number of subcarriers detected: {n_sc}")
    
    # Extract I and Q values and build complex numbers
    all_complex = []
    
    for idx in range(len(df)):
        row = df.iloc[idx]
        
        # Extract I and Q for each subcarrier
        i_vals = []
        q_vals = []
        
        for sc in range(n_sc):
            i_vals.append(row[f'sc{sc}_re'])
            q_vals.append(row[f'sc{sc}_im'])
        
        # Convert to complex
        complex_csi = np.array(i_vals, dtype=np.float64) + 1j * np.array(q_vals, dtype=np.float64)
        all_complex.append(complex_csi)
    
    # Convert to numpy array
    csi_array = np.array(all_complex)
    
    # Extract metadata
    metadata = {
        'sequence': seq_nums[0] if len(np.unique(seq_nums)) == 1 else 'Multiple',
        'core': cores[0] if len(np.unique(cores)) == 1 else 'Multiple',
        'nss': spatial_streams[0] if len(np.unique(spatial_streams)) == 1 else 'Multiple',
        'chanspec': 'CSV',  # Not available in CSV
        'chipver': 'CSV',   # Not available in CSV
        'n_packets': len(df),
        'n_subcarriers': n_sc,
        'duration': timestamps[-1] - timestamps[0],
        'rate': len(df) / (timestamps[-1] - timestamps[0]),
    }
    
    return csi_array, metadata


def plot_csi_metrics(csi_data, metadata, output_dir='graphs'):
    """Create comprehensive CSI plots (same as plot_csi.py)"""
    
    n_packets, n_subcarriers = csi_data.shape
    
    print(f"Processing {n_packets} packets with {n_subcarriers} subcarriers each")
    
    # Calculate metrics
    magnitudes = np.abs(csi_data)  # Amplitude
    phases = np.angle(csi_data)    # Phase in radians
    
    mean_magnitude = np.mean(magnitudes, axis=0)
    var_magnitude = np.var(magnitudes, axis=0)
    std_magnitude = np.std(magnitudes, axis=0)
    
    # Create figure with subplots
    fig = plt.figure(figsize=(15, 12))
    
    # 1. Mean CSI Magnitude per subcarrier
    ax1 = plt.subplot(2, 2, 1)
    subcarriers = np.arange(n_subcarriers)
    ax1.plot(subcarriers, mean_magnitude, 'b-', linewidth=1.5)
    ax1.set_xlabel('Subcarrier Index')
    ax1.set_ylabel('Mean Magnitude')
    ax1.set_title(f'Mean CSI Magnitude per Subcarrier (n={n_packets} packets)')
    ax1.grid(True, alpha=0.3)
    
    # 2. CSI Variance per subcarrier
    ax2 = plt.subplot(2, 2, 2)
    ax2.plot(subcarriers, var_magnitude, 'r-', linewidth=1.5)
    ax2.set_xlabel('Subcarrier Index')
    ax2.set_ylabel('Variance')
    ax2.set_title(f'CSI Variance per Subcarrier')
    ax2.grid(True, alpha=0.3)
    
    # 3. CSI Amplitude (Magnitude) for all packets per subcarrier (heatmap)
    ax3 = plt.subplot(2, 2, 3)
    # Use a subset of packets if too many
    max_packets_to_plot = min(n_packets, 500)
    step = max(1, n_packets // max_packets_to_plot)
    magnitudes_subset = magnitudes[::step, :]
    
    im = ax3.imshow(magnitudes_subset.T, aspect='auto', cmap='viridis', 
                    extent=[0, len(magnitudes_subset), 0, n_subcarriers])
    ax3.set_xlabel('Packet Number')
    ax3.set_ylabel('Subcarrier Index')
    ax3.set_title(f'CSI Amplitude Heatmap (showing {len(magnitudes_subset)} packets)')
    plt.colorbar(im, ax=ax3, label='Magnitude')
    
    # 4. CSI Phase for all packets per subcarrier (heatmap)
    ax4 = plt.subplot(2, 2, 4)
    phases_subset = phases[::step, :]
    
    im2 = ax4.imshow(phases_subset.T, aspect='auto', cmap='hsv', 
                     extent=[0, len(phases_subset), 0, n_subcarriers],
                     vmin=-np.pi, vmax=np.pi)
    ax4.set_xlabel('Packet Number')
    ax4.set_ylabel('Subcarrier Index')
    ax4.set_title(f'CSI Phase Heatmap (showing {len(phases_subset)} packets)')
    plt.colorbar(im2, ax=ax4, label='Phase (radians)')
    
    plt.suptitle(f'CSI Analysis (from CSV) - {n_packets} Packets, {n_subcarriers} Subcarriers\n'
                 f'Duration: {metadata["duration"]:.1f}s, Rate: {metadata["rate"]:.1f} Hz, '
                 f'Core: {metadata["core"]}, Stream: {metadata["nss"]}', 
                 fontsize=14, fontweight='bold')
    
    # Create output directory if it doesn't exist
    Path(output_dir).mkdir(exist_ok=True)
    
    plt.tight_layout()
    plt.savefig(f'{output_dir}/csv_csi_analysis.png', dpi=300, bbox_inches='tight')
    print("Saved plot to 'graphs/csv_csi_analysis.png'")
    plt.close()
    
    return fig


def plot_csi_over_time(csi_data, packet_indices=None, subcarrier_indices=None, output_dir='graphs'):
    """Plot CSI magnitude and phase over time for specific subcarriers"""
    
    n_packets, n_subcarriers = csi_data.shape
    
    if packet_indices is None:
        packet_indices = np.arange(n_packets)
    
    if subcarrier_indices is None:
        # Select 5 representative subcarriers
        step = max(1, n_subcarriers // 5)
        subcarrier_indices = np.arange(0, n_subcarriers, step)[:5]
        # Also ensure we include subcarrier 0 and 1 (usually strong)
        if 0 not in subcarrier_indices:
            subcarrier_indices[0] = 0
        if 1 not in subcarrier_indices and n_subcarriers > 1:
            subcarrier_indices[1] = 1
    
    magnitudes = np.abs(csi_data)
    phases = np.angle(csi_data)
    
    # Create time series plot
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(14, 10))
    
    # Plot magnitude over time
    for idx in subcarrier_indices:
        ax1.plot(packet_indices, magnitudes[packet_indices, idx], 
                label=f'Subcarrier {idx}', linewidth=1.5, alpha=0.7)
    ax1.set_xlabel('Packet Number')
    ax1.set_ylabel('Magnitude')
    ax1.set_title('CSI Magnitude Over Time for Selected Subcarriers')
    ax1.legend()
    ax1.grid(True, alpha=0.3)
    
    # Plot phase over time
    for idx in subcarrier_indices:
        ax2.plot(packet_indices, phases[packet_indices, idx], 
                label=f'Subcarrier {idx}', linewidth=1.5, alpha=0.7)
    ax2.set_xlabel('Packet Number')
    ax2.set_ylabel('Phase (radians)')
    ax2.set_title('CSI Phase Over Time for Selected Subcarriers')
    ax2.legend()
    ax2.grid(True, alpha=0.3)
    
    plt.suptitle(f'CSI Time Series Analysis - {len(subcarrier_indices)} Selected Subcarriers', 
                 fontsize=14, fontweight='bold')
    plt.tight_layout()
    
    Path(output_dir).mkdir(exist_ok=True)
    plt.savefig(f'{output_dir}/csv_csi_timeseries.png', dpi=300, bbox_inches='tight')
    print("Saved plot to 'graphs/csv_csi_timeseries.png'")
    plt.close()
    
    return fig


def plot_statistical_summary(csi_data, output_dir='graphs'):
    """Create statistical summary plots"""
    
    n_packets, n_subcarriers = csi_data.shape
    
    magnitudes = np.abs(csi_data)
    phases = np.angle(csi_data)
    
    fig, ((ax1, ax2), (ax3, ax4)) = plt.subplots(2, 2, figsize=(14, 10))
    
    # Distribution of magnitudes for all subcarriers
    ax1.hist(magnitudes.flatten(), bins=100, alpha=0.7, color='blue', edgecolor='black')
    ax1.set_xlabel('Magnitude')
    ax1.set_ylabel('Frequency')
    ax1.set_title('Distribution of All CSI Magnitudes')
    ax1.grid(True, alpha=0.3)
    
    # Distribution of phases for all subcarriers
    ax2.hist(phases.flatten(), bins=100, alpha=0.7, color='red', edgecolor='black')
    ax2.set_xlabel('Phase (radians)')
    ax2.set_ylabel('Frequency')
    ax2.set_title('Distribution of All CSI Phases')
    ax2.grid(True, alpha=0.3)
    
    # Box plot of magnitudes per subcarrier
    # Only show a subset if too many subcarriers
    if n_subcarriers > 50:
        step = max(1, n_subcarriers // 50)
        subcarriers_to_show = np.arange(0, n_subcarriers, step)
        data_to_plot = magnitudes[:, subcarriers_to_show]
        ax3.boxplot(data_to_plot, positions=subcarriers_to_show, widths=0.8, 
                    showfliers=False, patch_artist=True)
        ax3.set_xlabel('Subcarrier Index')
        ax3.set_ylabel('Magnitude')
        ax3.set_title(f'Magnitude Distribution per Subcarrier (showing {len(subcarriers_to_show)} subcarriers)')
    else:
        ax3.boxplot(magnitudes.T, patch_artist=True)
        ax3.set_xlabel('Subcarrier Index')
        ax3.set_ylabel('Magnitude')
        ax3.set_title('Magnitude Distribution per Subcarrier')
    ax3.grid(True, alpha=0.3)
    
    # Mean and std dev of magnitudes across packets
    mean_mag = np.mean(magnitudes, axis=0)
    std_mag = np.std(magnitudes, axis=0)
    ax4.plot(mean_mag, 'b-', label='Mean', linewidth=2)
    ax4.fill_between(np.arange(n_subcarriers), 
                     mean_mag - std_mag, mean_mag + std_mag, 
                     alpha=0.3, color='blue', label='±1 Std Dev')
    ax4.set_xlabel('Subcarrier Index')
    ax4.set_ylabel('Magnitude')
    ax4.set_title('Mean Magnitude with Standard Deviation Bands')
    ax4.legend()
    ax4.grid(True, alpha=0.3)
    
    plt.suptitle(f'Statistical Summary - {n_packets} Packets, {n_subcarriers} Subcarriers', 
                 fontsize=14, fontweight='bold')
    plt.tight_layout()
    
    Path(output_dir).mkdir(exist_ok=True)
    plt.savefig(f'{output_dir}/csv_csi_statistics.png', dpi=300, bbox_inches='tight')
    print("Saved plot to 'graphs/csv_csi_statistics.png'")
    plt.close()
    
    return fig


def plot_motion_detection(csi_data, window=50, output_dir='graphs'):
    """Additional plot: Motion detection over time (like live_monitor.py)"""
    
    n_packets, n_subcarriers = csi_data.shape
    
    magnitudes = np.abs(csi_data)
    
    # Calculate rolling motion score
    motion_scores = []
    for i in range(window, n_packets):
        window_data = magnitudes[i-window:i]
        per_sc_std = np.std(window_data, axis=0)
        mean_amp = np.mean(window_data)
        score = np.mean(per_sc_std) / mean_amp if mean_amp > 0 else 0
        motion_scores.append(score)
    
    motion_scores = np.array(motion_scores)
    
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(12, 10))
    
    # Motion score over time
    ax1.plot(motion_scores, 'b-', linewidth=1)
    ax1.axhline(y=np.mean(motion_scores[:min(50, len(motion_scores))]), 
                color='g', linestyle='--', label='Baseline')
    ax1.axhline(y=np.mean(motion_scores[:min(50, len(motion_scores))]) * 1.5, 
                color='r', linestyle='--', label='Threshold (1.5x)')
    ax1.set_xlabel('Packet Number')
    ax1.set_ylabel('Motion Score')
    ax1.set_title(f'Motion Score Over Time (window={window} packets)')
    ax1.legend()
    ax1.grid(True, alpha=0.3)
    
    # Mean magnitude over time
    mean_mags = np.mean(magnitudes, axis=1)
    ax2.plot(mean_mags, 'r-', linewidth=1)
    ax2.set_xlabel('Packet Number')
    ax2.set_ylabel('Mean Magnitude')
    ax2.set_title('Average CSI Magnitude Over Time')
    ax2.grid(True, alpha=0.3)
    
    plt.suptitle('Motion Detection Analysis', fontsize=14, fontweight='bold')
    plt.tight_layout()
    
    Path(output_dir).mkdir(exist_ok=True)
    plt.savefig(f'{output_dir}/csv_motion_detection.png', dpi=300, bbox_inches='tight')
    print("Saved plot to 'graphs/csv_motion_detection.png'")
    plt.close()
    
    # Print statistics
    print(f"\nMotion Detection Statistics:")
    print(f"  Baseline (first 50 packets): {np.mean(motion_scores[:50]):.5f}")
    print(f"  Peak motion: {np.max(motion_scores):.5f}")
    print(f"  Motion score range: {np.min(motion_scores):.5f} to {np.max(motion_scores):.5f}")
    ratio = np.mean(motion_scores[50:]) / np.mean(motion_scores[:50]) if len(motion_scores) > 50 else 1
    print(f"  Ratio (after/before): {ratio:.3f}x")
    if ratio > 1.5:
        print("  ** MOTION / CHANGE DETECTED **")
    
    return fig


def plot_subcarrier_heatmap(csi_data, subcarrier_range=None, output_dir='graphs'):
    """Plot detailed heatmap for specific subcarrier range"""
    
    n_packets, n_subcarriers = csi_data.shape
    
    if subcarrier_range is None:
        # Default: show all subcarriers
        sc_start = 0
        sc_end = n_subcarriers
    else:
        sc_start, sc_end = subcarrier_range
    
    magnitudes = np.abs(csi_data)
    phases = np.angle(csi_data)
    
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(14, 10))
    
    # Magnitude heatmap
    im1 = ax1.imshow(magnitudes[:, sc_start:sc_end].T, aspect='auto', cmap='viridis')
    ax1.set_xlabel('Packet Number')
    ax1.set_ylabel('Subcarrier Index')
    ax1.set_title(f'CSI Magnitude Heatmap (Subcarriers {sc_start}-{sc_end-1})')
    plt.colorbar(im1, ax=ax1, label='Magnitude')
    
    # Phase heatmap
    im2 = ax2.imshow(phases[:, sc_start:sc_end].T, aspect='auto', cmap='hsv', vmin=-np.pi, vmax=np.pi)
    ax2.set_xlabel('Packet Number')
    ax2.set_ylabel('Subcarrier Index')
    ax2.set_title(f'CSI Phase Heatmap (Subcarriers {sc_start}-{sc_end-1})')
    plt.colorbar(im2, ax=ax2, label='Phase (radians)')
    
    plt.suptitle('Subcarrier Detail View', fontsize=14, fontweight='bold')
    plt.tight_layout()
    
    Path(output_dir).mkdir(exist_ok=True)
    plt.savefig(f'{output_dir}/csv_subcarrier_detail.png', dpi=300, bbox_inches='tight')
    print("Saved plot to 'graphs/csv_subcarrier_detail.png'")
    plt.close()
    
    return fig


def main():
    if len(sys.argv) != 2:
        print(f"Usage: python {sys.argv[0]} csi_capture_*.csv")
        print("\nThis script creates the same plots as plot_csi.py but for CSV files")
        print("generated by live_monitor.py --capture-mode complex")
        print("\nExample:")
        print("  python plot_csv.py output/csi_capture_20240101_120000.csv")
        sys.exit(1)
    
    csv_file = sys.argv[1]
    
    if not Path(csv_file).exists():
        print(f"Error: File '{csv_file}' not found!")
        sys.exit(1)
    
    try:
        # Extract CSI data from CSV
        csi_data, metadata = extract_all_csi_from_csv(csv_file)
        
        if len(csi_data) == 0:
            print("No valid CSI data found!")
            sys.exit(1)
        
        n_packets, n_subcarriers = csi_data.shape
        print(f"Successfully extracted {n_packets} packets with {n_subcarriers} subcarriers each")
        
        # Print metadata
        print("\nMetadata:")
        print(f"  Duration: {metadata['duration']:.1f} seconds")
        print(f"  Rate: {metadata['rate']:.1f} Hz")
        print(f"  Core: {metadata['core']}")
        print(f"  Stream: {metadata['nss']}")
        print(f"  Sequence: {metadata['sequence']}")
        
        # Create output directory
        output_dir = 'graphs'
        Path(output_dir).mkdir(exist_ok=True)
        
        # Create the plots (matching plot_csi.py)
        print("\nGenerating plots...")
        
        # Plot 1: Main analysis plots (matches plot_csi.py)
        plot_csi_metrics(csi_data, metadata, output_dir)
        
        # Plot 2: Time series for selected subcarriers (matches plot_csi.py)
        plot_csi_over_time(csi_data, output_dir=output_dir)
        
        # Plot 3: Statistical summary (matches plot_csi.py)
        plot_statistical_summary(csi_data, output_dir)
        
        # Additional: Motion detection (new for CSV)
        plot_motion_detection(csi_data, output_dir=output_dir)
        
        # Additional: Subcarrier detail (new for CSV)
        # Show first 50 subcarriers in detail
        plot_subcarrier_heatmap(csi_data, subcarrier_range=(0, min(50, n_subcarriers)), output_dir=output_dir)
        
        print("\nAll plots generated successfully!")
        print(f"Files saved in '{output_dir}/':")
        print("  - csv_csi_analysis.png")
        print("  - csv_csi_timeseries.png")
        print("  - csv_csi_statistics.png")
        print("  - csv_motion_detection.png")
        print("  - csv_subcarrier_detail.png")
        
    except Exception as e:
        print(f"Error processing CSV: {e}")
        print("\nMake sure the CSV was generated with --capture-mode complex")
        print("The CSV should have columns: ts, seq_num, core, spatial_stream, sc0_re, sc0_im, ...")
        sys.exit(1)


if __name__ == "__main__":
    main()